def build_watchlist(n_persons: int = 2200, n_entities: int = 800, seed: int = 7, start: int = 1) -> list[Entry]:
    rng = random.Random(seed)
    entries: list[Entry] = []
    seen: set[str] = set()
    i = start
    while len(entries) < n_persons:
        culture = rng.choices(CULTURES, weights=[30, 25, 15, 18, 12])[0]
        name, _ = _person_name(rng, culture)
        if name in seen:
            continue
        seen.add(name)
        list_type = "pep" if rng.random() < 0.3 else "sanctions"
        aliases = []
        for _ in range(rng.choice([0, 0, 1, 1, 2, 3])):
            alias, _ops = perturb_person(rng, name, culture, rng.randint(1, 2), honorifics=False)
            if alias != name and alias not in aliases:
                aliases.append(alias)
        dob = _dob(rng)
        if rng.random() < 0.15:
            dob = dob[:4]
        if rng.random() < 0.05:
            dob = None
        nat = rng.choice(NATIONALITIES[culture]) if rng.random() > 0.04 else None
        program = rng.choice(["ILLUSTRATIVE-A", "ILLUSTRATIVE-B", "ILLUSTRATIVE-C"]) if list_type == "sanctions" else "PEP-T1"
        entries.append(Entry(f"WL-{i:05d}", "person", list_type, name, aliases, dob, nat, culture, program))
        i += 1
    n_ent = 0
    while n_ent < n_entities:
        culture = rng.choices(CULTURES, weights=[30, 25, 15, 18, 12])[0]
        name = _entity_name(rng, culture)
        if name in seen:
            continue
        seen.add(name)
        aliases = []
        if rng.random() < 0.4:
            alias, _ = perturb_entity(rng, name, 1)
            if alias != name:
                aliases.append(alias)
        entries.append(Entry(f"WL-{i:05d}", "entity", "sanctions", name, aliases, None,
                             rng.choice(NATIONALITIES[culture]), culture, rng.choice(["ILLUSTRATIVE-A", "ILLUSTRATIVE-C"])))
        i += 1
        n_ent += 1
    return entries


def build_customers(watchlist: list[Entry], n: int = 20_000, n_true_persons: int = 320, n_true_entities: int = 80,
                    n_namesakes: int = 160, seed: int = 11) -> list[Customer]:
    rng = random.Random(seed)
    persons = [e for e in watchlist if e.kind == "person"]
    entities = [e for e in watchlist if e.kind == "entity"]
    customers: list[Customer] = []

    for e in rng.sample(persons, n_true_persons):
        base = e.name if (not e.aliases or rng.random() < 0.8) else rng.choice(e.aliases)
        name, ops = perturb_person(rng, base, e.culture, rng.choices([1, 2, 3], weights=[45, 40, 15])[0])
        dob, dob_op = _vary_dob(rng, e.dob)
        r = rng.random()
        nat = e.nationality if r < 0.85 else None if r < 0.95 else rng.choice(ALL_NATIONALITIES)
        customers.append(Customer("", "person", name, dob, nat, e.id, ops + [dob_op]))

    for e in rng.sample(entities, n_true_entities):
        name, ops = perturb_entity(rng, e.name, rng.choice([1, 1, 2]))
        customers.append(Customer("", "entity", name, None, e.nationality if rng.random() < 0.85 else None, e.id, ops))

    # Namesakes: same or near-identical name, different person (different DOB and usually nationality).
    for e in rng.sample(persons, n_namesakes):
        name = e.name if rng.random() < 0.6 else perturb_person(rng, e.name, e.culture, 1)[0]
        dob = _dob(rng, 1950, 2004)
        nat = rng.choice(NATIONALITIES[e.culture]) if rng.random() < 0.5 else rng.choice(ALL_NATIONALITIES)
        customers.append(Customer("", "person", name, dob, nat, None, ["namesake"], namesake_of=e.id))

    n_rest = n - len(customers)
    n_rest_entities = int(n_rest * 0.15)
    for k in range(n_rest):
        culture = rng.choices(CULTURES, weights=[20, 15, 15, 20, 30])[0]
        if k < n_rest_entities:
            customers.append(Customer("", "entity", _entity_name(rng, culture), None, rng.choice(NATIONALITIES[culture])))
        else:
            name, _ = _person_name(rng, culture)
            customers.append(Customer("", "person", name, _dob(rng, 1940, 2005),
                                      rng.choice(NATIONALITIES[culture]) if rng.random() > 0.05 else None))
    rng.shuffle(customers)
    for idx, c in enumerate(customers, 1):
        c.id = f"C-{idx:06d}"
    return customers


def evolve_watchlist(watchlist: list[Entry], n_add: int = 40, n_modify: int = 25, n_remove: int = 15,
                     seed: int = 99) -> tuple[list[Entry], dict]:
    """Simulate a list update: new designations, amended entries (new aliases), and delistings."""
    rng = random.Random(seed)
    by_id = {e.id: Entry(**e.to_dict()) for e in watchlist}
    ids = sorted(by_id)
    removed = rng.sample(ids, n_remove)
    remaining = [i for i in ids if i not in set(removed)]
    modified = rng.sample(remaining, n_modify)
    for mid in modified:
        e = by_id[mid]
        alias = perturb_person(rng, e.name, e.culture, 2)[0] if e.kind == "person" else perturb_entity(rng, e.name, 1)[0]
        e.aliases = [*e.aliases, alias]
    for rid in removed:
        del by_id[rid]
    next_id = max(int(i[3:]) for i in ids) + 1
    added = build_watchlist(n_persons=n_add - n_add // 4, n_entities=n_add // 4, seed=seed + 1, start=next_id)
    for e in added:
        by_id[e.id] = e
    change = {"added": [e.id for e in added], "modified": modified, "removed": removed}
    return sorted(by_id.values(), key=lambda e: e.id), change
