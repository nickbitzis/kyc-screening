def _person_name(rng: random.Random, culture: str) -> tuple[str, bool]:
    """Return (name, female)."""
    given = rng.choice(GIVEN[culture])
    female = given in {"Yekaterina", "Tatyana", "Natalya", "Olga", "Elena", "Yulia", "Irina", "Svetlana", "Marina",
                       "María", "Carmen", "Lucía", "Isabel", "Patricia", "Rosa", "Beatriz", "Adriana", "Valeria",
                       "Anna", "Claire", "Sophie", "Laura", "Emma"}
    fam = rng.choice(FAMILY[culture])
    if culture == "arabic":
        middle = rng.choice(GIVEN["arabic"])
        prefix = "Al-" if rng.random() < 0.4 else ""
        return f"{given} {middle} {prefix}{fam}", False
    if culture == "cyrillic":
        father = rng.choice([g for g in GIVEN["cyrillic"][:21]])
        if female:
            fam = fam[:-1] + "aya" if fam.endswith("sky") else fam + "a" if fam[-2:] in ("ov", "ev", "in") else fam
            pat = father.rstrip("y") + ("ovna" if not father.endswith("y") else "evna")
        else:
            pat = father.rstrip("y") + ("ovich" if not father.endswith("y") else "evich")
        return (f"{given} {pat} {fam}" if rng.random() < 0.6 else f"{given} {fam}"), female
    if culture == "chinese":
        g = rng.choice(GIVEN["chinese"]) + (rng.choice(GIVEN["chinese"]).lower() if rng.random() < 0.7 else "")
        return f"{fam} {g}", False
    if culture == "hispanic":
        g2 = f" {rng.choice(GIVEN['hispanic'])}" if rng.random() < 0.3 else ""
        mat = rng.choice(FAMILY["hispanic"])
        return f"{given}{g2} {fam} {mat}", female
    g2 = f" {rng.choice(GIVEN['latin'])}" if rng.random() < 0.25 else ""
    return f"{given}{g2} {fam}", female


