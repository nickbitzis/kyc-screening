def typo(rng: random.Random, word: str) -> str:
    if len(word) < 4:
        return word
    i = rng.randint(1, len(word) - 2)
    op = rng.choice(["sub", "del", "swap", "dup"])
    if op == "sub":
        ch = word[i].lower()
        rep = rng.choice(KEYBOARD_NEIGHBORS.get(ch, "aeiou"))
        return word[:i] + rep + word[i + 1:]
    if op == "del":
        return word[:i] + word[i + 1:]
    if op == "swap":
        return word[:i] + word[i + 1] + word[i] + word[i + 2:]
    return word[:i] + word[i] + word[i:]


def _strip_accents(s: str) -> str:
    from .normalize import fold
    return "".join(fold(ch) if not ch.isupper() else fold(ch).upper() for ch in s)


def _translit_person(rng: random.Random, parts: list[str], culture: str) -> list[str]:
    out = list(parts)
    idxs = list(range(len(out)))
    rng.shuffle(idxs)
    for i in idxs:
        p = out[i]
        base = p.replace("Al-", "")
        if base in GIVEN_VARIANTS:
            out[i] = p.replace(base, rng.choice(GIVEN_VARIANTS[base]))
            return out
        if culture == "chinese":
            cap = base[:1].upper() + base[1:]
            for k, v in CHINESE_WG.items():
                if cap.startswith(k):
                    out[i] = v + base[len(k):]
                    return out
        if culture == "cyrillic":
            for a, b in (("sky", "skiy"), ("sky", "ski"), ("ov", "off"), ("ev", "eff"), ("kh", "h"), ("zh", "j"),
                         ("ch", "tch"), ("shch", "sch"), ("ya", "ia"), ("yu", "iu"), ("ov", "ow")):
                if a in base.lower():
                    out[i] = base.replace(a, b, 1) if a in base else base
                    if out[i] != base:
                        return out
        if culture == "arabic":
            for a, b in (("ou", "u"), ("q", "k"), ("dh", "z"), ("aa", "a"), ("ee", "i"), ("ss", "s")):
                if a in base:
                    out[i] = p.replace(base, base.replace(a, b, 1))
                    return out
    return out


def perturb_person(rng: random.Random, name: str, culture: str, n_ops: int,
                   honorifics: bool = True) -> tuple[str, list[str]]:
    parts = name.split()
    applied: list[str] = []
    choices = ["translit", "translit", "typo", "swap", "drop", "initial", "diacritics", "spacing"]
    if honorifics:
        choices.append("honorific")
    if culture == "hispanic":
        choices += ["compound", "compound"]
    if culture == "chinese":
        choices += ["split_given", "translit"]
    honorific = None
    for op in rng.sample(choices, k=min(n_ops, len(choices))):
        if op in applied:
            continue
        if op == "translit":
            new = _translit_person(rng, parts, culture)
            if new == parts:
                continue
            parts = new
        elif op == "typo":
            i = rng.randrange(len(parts))
            parts[i] = typo(rng, parts[i])
        elif op == "swap" and len(parts) >= 2:
            parts = parts[-1:] + parts[:-1] if rng.random() < 0.5 else [parts[1], parts[0], *parts[2:]]
            if culture != "chinese" and rng.random() < 0.5:
                parts[0] = parts[0] + ","
        elif op == "drop" and len(parts) >= 3:
            parts.pop(rng.randrange(1, len(parts) - 1) if culture != "hispanic" else len(parts) - 1)
        elif op == "initial" and len(parts) >= 2:
            i = 0 if culture != "chinese" else len(parts) - 1
            if len(parts[i]) > 2:
                parts[i] = parts[i][0] + "."
        elif op == "honorific":
            honorific = rng.choice(HONORIFIC_PREFIXES)
        elif op == "diacritics":
            stripped = [_strip_accents(p) for p in parts]
            if stripped != parts:
                parts = stripped
            else:
                parts = [p.replace("e", "é", 1) if j == len(parts) - 1 else p for j, p in enumerate(parts)]
        elif op == "spacing":
            joined = " ".join(parts)
            if "Al-" in joined:
                joined = joined.replace("Al-", rng.choice(["Al ", "Al", "El-", "al-"]))
            else:
                joined = joined.upper()
            parts = joined.split()
        elif op == "compound" and len(parts) >= 3:
            r = rng.random()
            if r < 0.4:
                parts = parts[:-2] + [parts[-2] + "-" + parts[-1]]
            elif r < 0.7:
                parts = parts[:-1] + ["y", parts[-1]]
            else:
                parts = parts[:-1]
        elif op == "split_given" and len(parts) == 2 and len(parts[1]) > 4:
            g = parts[1]
            cut = max(2, len(g) // 2)
            parts = [parts[0], g[:cut], g[cut:].capitalize()] if rng.random() < 0.5 else [parts[0], g[:cut] + "-" + g[cut:]]
        else:
            continue
        applied.append(op)
    out = " ".join(parts)
    if honorific:
        out = f"{honorific} {out}"
    return out, applied


def perturb_entity(rng: random.Random, name: str, n_ops: int) -> tuple[str, list[str]]:
    applied: list[str] = []
    s = name
    for op in rng.sample(["suffix", "suffix", "typo", "drop_word", "abbrev", "the", "spacing", "translit"], k=n_ops):
        if op in applied:
            continue
        words = s.split()
        if op == "suffix":
            cur = [suf for suf in sorted({x for v in LEGAL_SUFFIX.values() for x in v}, key=len, reverse=True)
                   if s.endswith(" " + suf)]
            base = s[: -len(cur[0]) - 1] if cur else s
            s = f"{base} {rng.choice(SUFFIX_SWAPS)}".strip()
        elif op == "typo":
            i = rng.randrange(len(words))
            words[i] = typo(rng, words[i])
            s = " ".join(words)
        elif op == "drop_word" and len(words) >= 4:
            words.pop(rng.randrange(1, len(words) - 1))
            s = " ".join(words)
        elif op == "abbrev":
            s = s.replace("General Trading", "Gen. Trading").replace("Import Export", "Imp. & Exp.")
        elif op == "the":
            s = "The " + s
        elif op == "spacing":
            s = s.upper() if rng.random() < 0.5 else s.replace("Al ", "Al-").replace("Al Noor", "Alnoor")
        elif op == "translit":
            s = s.replace("Huaxin", "Hua Xin").replace("Jinlong", "Chin Lung").replace("Volga", "Wolga")
        else:
            continue
        applied.append(op)
    return s.strip(), applied


def _vary_dob(rng: random.Random, dob: str | None) -> tuple[str | None, str]:
    if dob is None:
        return None, "dob_missing"
    r = rng.random()
    if r < 0.08:
        return None, "dob_missing"
    if len(dob) == 4:
        return f"{dob}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}", "dob_year_only"
    y, m, d = dob.split("-")
    if r < 0.13 and int(d) <= 12:
        return f"{y}-{d}-{m}", "dob_day_month_swap"
    if r < 0.17:
        return f"{int(y) + rng.choice([-1, 1])}-{m}-{d}", "dob_year_off"
    return dob, "dob_same"


